-- 接入流水：整包原文 + 逐项清洗结果，用于异常现场回放。
-- 默认永久保留（retention_days NULL）；只有显式配置天数后才按天 drop 过期分区。

create table if not exists raw_retention (
    id             smallint primary key,
    retention_days int check (retention_days is null or retention_days > 0),
    updated_at     timestamptz not null default now()
);
insert into raw_retention (id, retention_days) values (1, null)
on conflict (id) do nothing;

create table if not exists raw_message (
    id             bigint generated by default as identity,
    gateway_id     text        not null,
    source         text        not null,
    received_at    timestamptz not null,
    payload        jsonb       not null,
    terminal_count int         not null,
    byte_size      int         not null,
    primary key (id, received_at)
) partition by range (received_at);

create table if not exists raw_item (
    id             bigint generated by default as identity,
    message_id     bigint      not null,
    received_at    timestamptz not null,
    terminal_id    text        not null,
    item_code      text        not null,
    value_num      double precision,
    value_text     text,
    unit           text,
    value_time     timestamptz,
    quality        smallint    not null default 0,
    quality_reason text,
    status         text        not null check (status in ('written', 'dropped', 'ignored')),
    reason         text,
    raw_value      jsonb,
    primary key (id, received_at)
) partition by range (received_at);

create index if not exists raw_item_terminal_time_idx
    on raw_item (terminal_id, received_at desc);
create index if not exists raw_item_terminal_code_time_idx
    on raw_item (terminal_id, item_code, received_at desc);

-- 初始分区：当天 ~ +3 天；续建与清理由后台任务负责。
do $$
declare d date;
begin
    for d in select generate_series(current_date, current_date + 3, interval '1 day')::date loop
        execute format(
            'create table if not exists raw_message_%s partition of raw_message for values from (%L) to (%L)',
            to_char(d, 'YYYYMMDD'), d, d + 1);
        execute format(
            'create table if not exists raw_item_%s partition of raw_item for values from (%L) to (%L)',
            to_char(d, 'YYYYMMDD'), d, d + 1);
    end loop;
end $$;


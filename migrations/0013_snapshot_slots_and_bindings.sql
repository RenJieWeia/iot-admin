-- 快照配置：从「每序列一行 + 六个档位列」改为「全局六档 + 绑定表」。
--
-- 旧模型 snapshot_plan 的语义是「一条记录既描述**哪些序列**要快照，又描述**每档怎么配**」，
-- 两件事耦合在一行里：新增一台终端要复制一行配置，改某个档的步长要逐行改。
-- 新模型把两件事拆开：
--   snapshot_slot_config  六行固定，全局唯一（哪几档开、每档步长多少）；
--   snapshot_binding      一条 = 一个数据项被纳入快照（类型级或实例级）。
-- **两者语义不等价**，旧配置无法自动映射：旧行的六个 enabled 是"这条序列各档怎么开"，
-- 新模型的 enabled 是全局的；旧行里哪些序列算"已纳入"也无法与新绑定一一对应。
-- 因此存量配置按**丢弃**处理（本迁移直接 drop table snapshot_plan），不做数据迁移。
--
-- 三张快照表的结构与写入语义不变；保留期仍在 snapshot_settings（三行按表），本迁移不动。

-- ── 全局六档配置：六行固定 ──────────────────────────────────────────────────
create table if not exists snapshot_slot_config (
    granularity text primary key check (granularity in ('second', 'minute', 'hour', 'day', 'month', 'year')),
    enabled     boolean     not null default false,
    step        int,
    updated_at  timestamptz not null default now(),
    -- 步长白名单按档位分别约束，与 0010 的 CHECK 同源；
    -- 未启用时允许 step 为空，启用时必须给出合法步长（见下面的约束）。
    check (
        case granularity
            when 'second' then step is null or step in (1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30)
            when 'minute' then step is null or step in (1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30)
            when 'hour'   then step is null or step in (1, 2, 3, 4, 6, 8, 12)
            when 'day'    then step is null or step = 1
            when 'month'  then step is null or step in (1, 2, 3, 4, 6, 12)
            when 'year'   then step is null or step = 1
            else false
        end
    ),
    check (not enabled or step is not null)
);

insert into snapshot_slot_config (granularity, enabled, step) values
    ('second', false, null),
    ('minute', false, null),
    ('hour',   false, null),
    ('day',    false, null),
    ('month',  false, null),
    ('year',   false, null)
on conflict (granularity) do nothing;

-- ── 绑定：一条 = 一个数据项被纳入快照 ────────────────────────────────────────
create table if not exists snapshot_binding (
    id             bigint generated by default as identity primary key,
    device_type_id bigint      references device_type (id) on delete cascade,
    terminal_id    text        references terminal (id) on delete cascade,
    item_code      text        not null,
    created_at     timestamptz not null default now(),
    -- 作用域二选一：类型级（该类型下所有终端）或实例级（指定终端）。
    check ((device_type_id is null) <> (terminal_id is null))
);

-- 同一类型下的同一数据项只能绑定一次；同一终端的同一数据项只能绑定一次。
-- 用部分唯一索引而不是普通唯一约束：另一列为 NULL，普通唯一约束对 NULL 不去重。
create unique index if not exists snapshot_binding_type_uk
    on snapshot_binding (device_type_id, item_code) where device_type_id is not null;

create unique index if not exists snapshot_binding_terminal_uk
    on snapshot_binding (terminal_id, item_code) where terminal_id is not null;

create index if not exists snapshot_binding_item_idx on snapshot_binding (item_code);

-- ── 旧模型下线（配置按丢弃处理，见文件头说明）────────────────────────────────
drop table if exists snapshot_plan;

-- 数据源元模型（管理 API 读写）。
-- terminal.id 直接使用上报消息里的 terminalId（终端编码），与 latest_value / hourly_* 的 terminal_id 同构。
create table if not exists data_domain (
    id   bigint generated by default as identity primary key,
    code text not null unique,
    name text not null
);

create table if not exists device_type (
    id        bigint generated by default as identity primary key,
    code      text not null unique,
    name      text not null,
    domain_id bigint not null references data_domain (id)
);

create table if not exists thing_model_property (
    id         bigint generated by default as identity primary key,
    type_id    bigint not null references device_type (id) on delete cascade,
    item_code  text not null,
    name       text not null,
    value_type text not null check (value_type in ('number', 'string', 'bool')),
    unit       text,
    precision  int check (precision is null or precision >= 0),
    required   boolean not null default false,
    min_value  double precision,
    max_value  double precision,
    unique (type_id, item_code)
);

create table if not exists terminal (
    id         text primary key,
    type_id    bigint not null references device_type (id),
    gateway_id text not null,
    name       text,
    enabled    boolean not null default true
);

create index if not exists terminal_gateway_idx on terminal (gateway_id);

-- rule_type 闭集与 internal/clean/rules.go 中的定义保持一致，禁止扩展。
create table if not exists quality_rule (
    id          bigint generated by default as identity primary key,
    terminal_id text not null,
    item_code   text not null,
    rule_type   text not null check (rule_type in ('range', 'enum', 'precision', 'unit_whitelist', 'not_null')),
    params      jsonb not null default '{}'::jsonb,
    enabled     boolean not null default true,
    unique (terminal_id, item_code, rule_type)
);

-- 结算窗口：type_id 精确匹配 > domain_id 匹配 > 全局行（两者都 NULL，默认 900 秒）。
create table if not exists settle_config (
    id             bigint generated by default as identity primary key,
    domain_id      bigint references data_domain (id),
    type_id        bigint references device_type (id),
    window_seconds int not null check (window_seconds > 0 and window_seconds <= 86400)
);

create unique index if not exists settle_config_type_uq
    on settle_config (type_id) where type_id is not null;
create unique index if not exists settle_config_domain_uq
    on settle_config (domain_id) where type_id is null and domain_id is not null;
create unique index if not exists settle_config_global_uq
    on settle_config ((true)) where type_id is null and domain_id is null;

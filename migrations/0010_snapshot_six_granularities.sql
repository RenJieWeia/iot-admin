-- 六档自然时间快照：粗表（时/日/月/年）+ 分表 + 秒表 + 白名单 + 保留期。
--
-- 口径（与需求定稿一致）：
--   * 段起点对齐 +08:00 本地自然时间；秒/分/时按 step 对齐，日/月/年按本地边界对齐。
--   * 每段只保留「段内采集时间最新的一条」，覆盖式写入，revision 作覆盖计数。
--   * 迟到按档独立判：段结束 + 15 分钟；超时该档不写，其余档照写。
--   * 三表各一个保留期（snapshot_settings），空值 = 永久保留。
--
-- 分区键取 segment_start（段起点），不是 updated_at：
--   1) PG 要求分区表的唯一约束/主键必须包含分区键。若按 updated_at 分区，自然键
--      (terminal_id,item_code,[granularity,]segment_start) 就无法做主键，"覆盖式写入"
--      的 ON CONFLICT 也无从下手；若把 updated_at 塞进主键，每段会变成多行，语义就散了。
--      改为每次覆盖都「更新分区键」则要跨分区移动行，秒表热路径上是纯亏。
--   2) 段起点天然是「这一段属于哪个时间段」的判定依据，保留期按段起点裁剪可解释。
--   已知代价（已接受）：年档 segment_start 恒为某年 1 月 1 日，会与同年第 1 个月的
--   其它粗档共用一个分区；年档行数只有 O(序列数/年)，对分区均衡的影响可忽略。
--   秒表用日分区（短保留可用整日 DROP 表达），粗表/分表用月分区（保留期以年计）。
--
-- 初始分区窗口由本迁移按「当前时间」铺出，运行期由维护任务续建；
-- 缺分区时插入会失败 → 该终端 internal_error → 整包 503（平台故障语义，可重传）。

-- ── 粗表：小时 / 日 / 月 / 年 ───────────────────────────────────────────────
create table if not exists snapshot_coarse (
    terminal_id    text        not null,
    item_code      text        not null,
    granularity    text        not null check (granularity in ('hour', 'day', 'month', 'year')),
    segment_start  timestamptz not null,
    value_num      double precision,
    value_text     text,
    unit           text,
    value_time     timestamptz not null,
    quality        smallint    not null default 0,
    quality_reason text,
    revision       int         not null default 0,
    updated_at     timestamptz not null default now(),
    primary key (terminal_id, item_code, granularity, segment_start)
) partition by range (segment_start);

-- 后台「按档 + 时间窗」扫描（如「本月所有日档」）与清理统计用。
create index if not exists snapshot_coarse_granularity_idx
    on snapshot_coarse (granularity, segment_start);

-- ── 分表：只有「分」一档 ────────────────────────────────────────────────────
create table if not exists snapshot_minute (
    terminal_id    text        not null,
    item_code      text        not null,
    segment_start  timestamptz not null,
    value_num      double precision,
    value_text     text,
    unit           text,
    value_time     timestamptz not null,
    quality        smallint    not null default 0,
    quality_reason text,
    revision       int         not null default 0,
    updated_at     timestamptz not null default now(),
    primary key (terminal_id, item_code, segment_start)
) partition by range (segment_start);

-- ── 秒表：只有「秒」一档 ────────────────────────────────────────────────────
create table if not exists snapshot_second (
    terminal_id    text        not null,
    item_code      text        not null,
    segment_start  timestamptz not null,
    value_num      double precision,
    value_text     text,
    unit           text,
    value_time     timestamptz not null,
    quality        smallint    not null default 0,
    quality_reason text,
    revision       int         not null default 0,
    updated_at     timestamptz not null default now(),
    primary key (terminal_id, item_code, segment_start)
) partition by range (segment_start);

-- ── 白名单：一行 = 一个序列（设备类型 + 数据项），六档各一组「启用 + 步长」──
-- 档位是列不是行：界面上不存在「新增档位」，删除某档就是把 enabled 置 false。
create table if not exists snapshot_plan (
    id             bigint generated by default as identity primary key,
    device_type_id bigint not null references device_type (id) on delete cascade,
    item_code      text   not null,
    second_enabled boolean not null default false,
    second_step    int,
    minute_enabled boolean not null default false,
    minute_step    int,
    hour_enabled   boolean not null default false,
    hour_step      int,
    day_enabled    boolean not null default false,
    day_step       int default 1,
    month_enabled  boolean not null default false,
    month_step     int,
    year_enabled   boolean not null default false,
    year_step      int default 1,
    updated_at     timestamptz not null default now(),
    unique (device_type_id, item_code),
    check (second_step is null or second_step in (1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30)),
    check (minute_step is null or minute_step in (1, 2, 3, 4, 5, 6, 10, 12, 15, 20, 30)),
    check (hour_step   is null or hour_step   in (1, 2, 3, 4, 6, 8, 12)),
    check (day_step    is null or day_step    = 1),
    check (month_step  is null or month_step  in (1, 2, 3, 4, 6, 12)),
    check (year_step   is null or year_step   = 1),
    -- 启用某档必须给步长，避免「开了但不知道多长」的悬空配置。
    check (not second_enabled or second_step is not null),
    check (not minute_enabled or minute_step is not null),
    check (not hour_enabled   or hour_step   is not null),
    check (not day_enabled    or day_step    is not null),
    check (not month_enabled  or month_step  is not null),
    check (not year_enabled   or year_step   is not null)
);

create index if not exists snapshot_plan_type_idx on snapshot_plan (device_type_id);

-- ── 保留期：表级配置，三行固定 ──────────────────────────────────────────────
-- 空值 = 永久保留（不建清理任务）。不是档位级配置，别放进 snapshot_plan。
create table if not exists snapshot_settings (
    table_name     text primary key check (table_name in ('snapshot_coarse', 'snapshot_minute', 'snapshot_second')),
    retention_days int check (retention_days is null or retention_days > 0),
    updated_at     timestamptz not null default now()
);

insert into snapshot_settings (table_name, retention_days) values
    ('snapshot_coarse', null),
    ('snapshot_minute', null),
    ('snapshot_second', null)
on conflict (table_name) do nothing;

-- ── 初始分区窗口（运行期由维护任务续建）────────────────────────────────────
do $$
declare
    m      date := date_trunc('month', now() at time zone 'Asia/Shanghai')::date;
    d      date := (now() at time zone 'Asia/Shanghai')::date;
    i      int;
    start_ts timestamptz;
    end_ts   timestamptz;
begin
    -- 粗表/分表：按段起点，回看 24 个月 + 未来 12 个月
    for i in -24..12 loop
        start_ts := ((m + make_interval(months => i))::timestamp at time zone 'Asia/Shanghai');
        end_ts   := ((m + make_interval(months => i + 1))::timestamp at time zone 'Asia/Shanghai');
        execute format(
            'create table if not exists snapshot_coarse_%s partition of snapshot_coarse for values from (%L) to (%L)',
            to_char(m + make_interval(months => i), 'YYYYMM'), start_ts, end_ts);
        execute format(
            'create table if not exists snapshot_minute_%s partition of snapshot_minute for values from (%L) to (%L)',
            to_char(m + make_interval(months => i), 'YYYYMM'), start_ts, end_ts);
    end loop;

    -- 秒表：按段起点，回看 30 天 + 未来 8 天（日分区，短保留才能整日 DROP）
    for i in -30..7 loop
        start_ts := ((d + i)::timestamp at time zone 'Asia/Shanghai');
        end_ts   := ((d + i + 1)::timestamp at time zone 'Asia/Shanghai');
        execute format(
            'create table if not exists snapshot_second_%s partition of snapshot_second for values from (%L) to (%L)',
            to_char(d + i, 'YYYYMMDD'), start_ts, end_ts);
    end loop;
end
$$;

-- R-034 补录留痕：版本记录表（不改 hourly_snapshot 结构，也不给它加 source 列）。
--
-- 只在"来源是补录"时写：msgType=2（MQTT 补录）或手工 API（source=2），
-- 且本次对快照实际产生了 insert 或 update（实时写入不写，否则与快照同量级）。
--
-- revision  : 这次写入**之后**的版本号，与 hourly_snapshot.revision 对齐（首次插入即补录时为 0）
-- source    : 1 = MQTT 补录（msgType=2）；2 = 手工 API
-- value_time: 本次写入的采集时间
-- actor     : 手工 API 的 operator（可空）
--
-- 保留期与快照同寿命：EnsurePartitions 的 dropExpired 同步删除 changed_at 早于保留截止月的版本行。
create table if not exists snapshot_cell_history (
    id          bigint generated by default as identity primary key,
    terminal_id text        not null,
    item_code   text        not null,
    hour_start  timestamptz not null,
    revision    int         not null,
    source      smallint    not null,
    value_time  timestamptz not null,
    changed_at  timestamptz not null default now(),
    actor       text
);

-- 某格的版本历史（本期不提供查询端点，索引先建好）
create index if not exists snapshot_cell_history_cell_idx
    on snapshot_cell_history (terminal_id, item_code, hour_start, revision desc);

-- 保留期清理用
create index if not exists snapshot_cell_history_changed_idx
    on snapshot_cell_history (changed_at);

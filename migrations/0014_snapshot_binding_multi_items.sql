-- 绑定改为「单目标 + 多字段」：一条绑定 = 一个作用域目标 + 一个数据项数组。
--
-- 0013 的模型是「一条 = 一个数据项」，同一目标要绑 5 个字段就得 5 行，列表变成噪音，
-- 编辑也只能逐行改。改为数组后：一条绑定整行原子更新，列表一行一个目标。
--
-- 为什么用 jsonb 数组而不是明细表：
--   绑定总量很小（目标数级，不是数据项级），数组能整行原子替换；
--   admin 侧已有 jsonb 列的 ::jsonb 转换机制，不引入新组件；
--   明细表要多一套子表 CRUD、排序与并发合并规则，收益不抵成本。
--
-- 0013 刚落库、数据量极小（本环境 3 行），按**重建**处理，不做列迁移。
-- 注意：这一 drop 会丢掉 0013 期间建的绑定，属于已接受的重建代价。

drop table if exists snapshot_binding;

create table snapshot_binding (
    id             bigint generated by default as identity primary key,
    device_type_id bigint      references device_type (id) on delete cascade,
    terminal_id    text        references terminal (id) on delete cascade,
    item_codes     jsonb       not null default '[]'::jsonb,
    created_at     timestamptz not null default now(),
    -- 作用域二选一：类型级（该类型下所有终端）或实例级（指定终端）。
    check ((device_type_id is null) <> (terminal_id is null)),
    -- 必须是非空字符串数组：空绑定没有意义（服务层还会做去重与物模型校验）。
    check (jsonb_typeof(item_codes) = 'array' and jsonb_array_length(item_codes) > 0)
);

-- 一个目标只能有一条绑定：类型级按类型唯一，实例级按终端唯一。
-- 部分唯一索引（另一列为 NULL），因为普通唯一约束对 NULL 不去重。
create unique index snapshot_binding_type_uk
    on snapshot_binding (device_type_id) where device_type_id is not null;

create unique index snapshot_binding_terminal_uk
    on snapshot_binding (terminal_id) where terminal_id is not null;

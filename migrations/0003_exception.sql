-- 异常两表：用途不同，禁止合并。
-- error_type 闭集与 internal/exception/errors.go 保持同步（状态型 -> interval，事件型 -> count）。
create extension if not exists btree_gist;

create table if not exists exception_interval (
    id          bigint generated by default as identity primary key,
    terminal_id text not null,
    gateway_id  text not null default '',
    item_code   text,
    error_type  text not null check (error_type in ('gateway_disconnected', 'auth_failed', 'item_silent')),
    period      tstzrange not null,
    raw_count   int not null default 1,
    created_at  timestamptz not null default now(),
    -- 同 (terminal, error_type, item_code) 上不允许两个区间重叠；item_code 为 NULL 时用 '' 参与比较，
    -- 否则 NULL 之间永不相等，会把"同一数据项静默"漏成双开。
    constraint exception_interval_no_overlap exclude using gist (
        terminal_id with =,
        error_type with =,
        coalesce(item_code, '') with =,
        period with &&
    )
);

-- 未结束的区间 = upper_inf(period)；本期不设自动关闭任务。
create index if not exists exception_interval_open_idx
    on exception_interval (terminal_id, error_type)
    where upper_inf(period);

create table if not exists exception_count (
    terminal_id   text not null,
    gateway_id    text not null default '',
    hour_start    timestamptz not null,
    error_type    text not null check (error_type in (
        'upload_timeout', 'protocol_error', 'msg_incomplete', 'clean_failed',
        'cache_write_failed', 'mqtt_publish_failed', 'snapshot_failed',
        'late_data', 'quality_violation'
    )),
    count         int not null default 0,
    sample_digest text,
    first_seen    timestamptz not null,
    last_seen     timestamptz not null,
    primary key (terminal_id, hour_start, error_type)
);

-- 快照查询模板：只查粗表（时/日/月/年），保存"终端类型 + 字段"的展示配置。
--
-- 模板不绑定档位与时间窗：同一模板在查询页可切换四个档位与时间范围。
-- 行 = 终端实例（按类型展开），列 = 终端字段（item_code）；
-- 单元格 = 所选档位/时间范围内该终端该字段的最新一条快照。
create table if not exists snapshot_query_template (
    id              bigint generated by default as identity primary key,
    name            text        not null,
    description     text        not null default '',
    device_type_ids jsonb       not null default '[]'::jsonb,
    item_codes      jsonb       not null default '[]'::jsonb,
    created_at      timestamptz not null default now(),
    updated_at      timestamptz not null default now(),
    check (jsonb_typeof(device_type_ids) = 'array'),
    check (jsonb_typeof(item_codes) = 'array')
);

create unique index if not exists snapshot_query_template_name_idx
    on snapshot_query_template (name);

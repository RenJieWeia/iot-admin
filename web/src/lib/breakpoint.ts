/**
 * 窄屏断点的唯一来源。
 *
 * 口径 = Tailwind `max-xl`（`< 1280px`，**不含 1280**）：1280 起算桌面（侧栏常驻），
 * 1279 及以下走窄屏（侧栏收进抽屉、筛选收进抽屉）。
 *
 * 为什么是 1280 而不是 1024：内容区可用宽度 = 视口 − 308（侧栏 220 + main 内边距 48 +
 * 内容卡片内边距 40）。1024~1279 这一段只剩 716~971px，放不下 6 列的表格最小宽度，
 * 表现为「右侧被切、要拖横向滚动条」。收起侧栏后可用宽度回到 视口 − 88，1024 下有 936+。
 *
 * 与 `styles/tailwind.css` 里 shell 的 `@media (max-width: 1279.98px)` 必须保持同一数值——
 * 差 1px 就会出现「CSS 已切单列、JS 仍认为桌面」的错位（历史缺陷，见 60bc623）。
 *
 * 注意：`touch-target` / `touch-hit` 里的 `1023.98px` **不是这个断点**，那是"触摸热区密度"，
 * 与"内容区窄到放不下侧栏"是两个语义，口径不同、各自独立（见 tailwind.css 里的注释）。
 */
export const NARROW_QUERY = '(max-width: 1279.98px)';
